#!/usr/bin/env python3
"""Generate rh_dev_gen.h for tools/rhost/rh_dev.c (the --headless fake devices).

For every COM interface the fakes expose, parse the mingw header's method list (vtable
order) and emit:
  - a default stub per method rh_dev.c does not implement itself: right stdcall size,
    counts the call (dev_note), returns 0 (S_OK);
  - the vtable `void *const vt_<Iface>[]`, slots pointing at `<Iface>_x_<Method>` (rh_dev.c)
    or the stub;
  - a _Static_assert per hand-written method: its type equals the header's vtable member.

usage: gen_dev.py rh_dev.c > rh_dev_gen.h
"""
import re, subprocess, sys

IFACES = [   # (interface, header)
    ("IDirect3D8", "d3d8.h"), ("IDirect3DDevice8", "d3d8.h"), ("IDirect3DTexture8", "d3d8.h"),
    ("IDirect3DSurface8", "d3d8.h"), ("IDirect3DVertexBuffer8", "d3d8.h"), ("IDirect3DIndexBuffer8", "d3d8.h"),
    ("IDirectMusicPerformance8", "dmusici.h"), ("IDirectMusicLoader8", "dmusici.h"),
    ("IDirectMusicSegment8", "dmusici.h"), ("IDirectMusicSegmentState8", "dmusici.h"),
    ("IDirectMusicAudioPath", "dmusici.h"),
    ("IGraphBuilder", "strmif.h"), ("IMediaControl", "control.h"), ("IVideoWindow", "control.h"),
    ("IMediaEventEx", "control.h"), ("IBasicAudio", "control.h"),
    ("IDirectInput8A", "dinput.h"), ("IDirectInputDevice8A", "dinput.h"),
]
WIDE = re.compile(r"^(?:const\s+)?(REFERENCE_TIME|__int64|LONGLONG|REFTIME|double|DATE)$")


def header_path(name):
    r = subprocess.run(["i686-w64-mingw32-gcc", "-xc", "-E", "-M", "-"], input=f"#include <windows.h>\n#include <{name}>\n",
                       capture_output=True, text=True)
    for tok in r.stdout.replace("\\\n", " ").split():
        if tok.endswith("/" + name):
            return tok
    raise SystemExit(f"cannot locate {name}")


def split_args(s):
    out, depth, cur = [], 0, ""
    for c in s:
        if c in "([":
            depth += 1
        elif c in ")]":
            depth -= 1
        if c == "," and depth == 0:
            out.append(cur); cur = ""
        else:
            cur += c
    if cur.strip():
        out.append(cur)
    return [a.strip() for a in out]


def arg_dwords(a):
    if a in ("void", ""):
        return 0
    t = re.sub(r"\b\w+\s*$", "", a).strip() or a          # drop the parameter name
    if "*" in t or "[" in a:
        return 1
    if re.search(r"\bVARIANT\b", t):
        raise SystemExit(f"by-value VARIANT argument: {a}")
    return 2 if WIDE.match(t) else 1


def parse(text, iface):
    """[(name, dwords incl. This)] in vtable order"""
    m = re.search(r"DECLARE_INTERFACE_(?:IID_)?\(\s*" + re.escape(iface) + r"\s*,.*?\{(.*?)\n\s*\};", text, re.S)
    methods = []
    if m:
        region = re.sub(r"\s*\n\s*", " ", m.group(1))
        for mm in re.finditer(r"STDMETHOD_\(\s*[^,]+?\s*,\s*(\w+)\s*\)\s*\(([^()]*)\)|STDMETHOD\(\s*(\w+)\s*\)\s*\(([^()]*)\)", region):
            name, args = (mm.group(1), mm.group(2)) if mm.group(1) else (mm.group(3), mm.group(4))
            args = re.sub(r"^\s*THIS_?\s*", "", args.strip())
            methods.append((name, 1 + sum(arg_dwords(a) for a in split_args(args))))
        return methods
    m = re.search(r"typedef struct " + re.escape(iface) + r"Vtbl\s*\{(.*?)END_INTERFACE", text, re.S)
    if not m:
        raise SystemExit(f"interface {iface} not found")
    for mm in re.finditer(r"\((?:STDMETHODCALLTYPE|WINAPI) \*(\w+)\)\(\s*([^;]*?)\);", m.group(1), re.S):
        args = split_args(re.sub(r"\s+", " ", mm.group(2)))
        methods.append((mm.group(1), 1 + sum(arg_dwords(a) for a in args[1:])))
    return methods


def main():
    src = open(sys.argv[1]).read()
    custom = set(re.findall(r"\b(I\w+?)_x_(\w+)\s*\(", src))
    for i in re.findall(r"^SIMPLE_UNK\((\w+)\)", src, re.M):          # macro-made methods
        custom |= {(i, m) for m in ("QueryInterface", "AddRef", "Release")}
    for i in re.findall(r"^BUF_METHODS\((\w+),", src, re.M):
        custom |= {(i, m) for m in ("QueryInterface", "AddRef", "Release", "GetDevice", "GetType", "Lock")}
    texts, out, notes = {}, ["/* GENERATED by tools/rhost/gen_dev.py — do not edit. */"], []
    body = []
    for iface, hdr in IFACES:
        if hdr not in texts:
            texts[hdr] = open(header_path(hdr), encoding="latin1").read()
        methods = parse(texts[hdr], iface)
        if [n for n, _ in methods[:3]] != ["QueryInterface", "AddRef", "Release"]:
            raise SystemExit(f"{iface}: vtable does not start with IUnknown ({methods[:3]})")
        body.append(f"/* ---- {iface}: {len(methods)} methods ---- */")
        slots = []
        for name, nd in methods:
            if (iface, name) in custom:
                slots.append(f"(void *){iface}_x_{name}")
                body.append(f"_Static_assert(__builtin_types_compatible_p(__typeof__(&{iface}_x_{name}), "
                            f"__typeof__((({iface}Vtbl *)0)->{name})), \"{iface}::{name} signature\");")
            else:
                idx = len(notes); notes.append(f"{iface}::{name}")
                params = ", ".join(f"DWORD a{i}" for i in range(nd))
                unused = " ".join(f"(void)a{i};" for i in range(nd))
                body.append(f"static HRESULT WINAPI gen_{iface}_{name}({params}) {{ {unused} dev_note({idx}); return 0; }}")
                slots.append(f"(void *)gen_{iface}_{name}")
        body.append(f"void *const vt_{iface}[] = {{\n    " + ",\n    ".join(slots) + "\n};")
    for c in sorted(custom):
        if not any(c[0] == i for i, _ in IFACES):
            raise SystemExit(f"{c[0]}_x_{c[1]}: unknown interface")
    out.append(f"#define DEV_NOTE_COUNT {len(notes)}")
    out.append("static const char *const g_note_names[DEV_NOTE_COUNT] = {\n    " + ",\n    ".join(f'"{n}"' for n in notes) + "\n};")
    out.append("static uint32_t g_note_calls[DEV_NOTE_COUNT];")
    out.append("static void dev_note(int i);")
    out += body
    print("\n".join(out))


if __name__ == "__main__":
    main()
