#!/usr/bin/env python3
"""rhost.log of a `--d3d-probe` run (real Direct3D 8) → tools/rhost/rh_dev_ref.h, the answers the
--headless device gives (rh_dev.c). Re-run when the reference machine's driver changes:

    python3 tools/rhost/rhost.py run house-idle --frames 200 --extra=" --d3d-probe"
    python3 tools/rhost/gen_dev_ref.py <run>/house-idle/rhost.log > tools/rhost/rh_dev_ref.h
"""
import sys

rows = [l.split() for l in open(sys.argv[1], encoding="latin1") if l.startswith("d3dref ")]
by = {}
for r in rows:
    by.setdefault(r[1], []).append(r[2:])
if "end" not in by or "devcaps" not in by:
    raise SystemExit("incomplete probe log (need `d3dref end` and `d3dref devcaps`)")


def blob(name, hexs):
    b = bytes.fromhex(hexs)
    body = ",".join(str(x) for x in b)
    return f"static const uint8_t {name}[{len(b)}] = {{{body}}};"


out = ["/* GENERATED by tools/rhost/gen_dev_ref.py from a --d3d-probe run on the reference machine",
       " * (Windows 11, d3d8 → d3d9 HAL). What the real Direct3D 8 answered; the --headless device repeats it. */"]
m = by["mode"][0]
out.append(f"static const D3DDISPLAYMODE REF_MODE = {{ {m[1]}, {m[2]}, {m[3]}, (D3DFORMAT){m[4]} }};")
en = by.get("enum", [])
out.append(f"static const struct {{ uint16_t w, h, hz, fmt; }} REF_MODES[{max(len(en), 1)}] = {{")
out += ["    " + " ".join(f"{{{e[1]},{e[2]},{e[3]},{e[4]}}}," for e in en[i:i + 8]) for i in range(0, len(en), 8)] or ["    {0,0,0,0}"]
out.append("};")
out.append(f"#define REF_NMODES {len(en)}")
caps = {c[0]: c for c in by["caps"]}
out.append(blob("REF_CAPS_HAL", caps["1"][3]))
out.append(blob("REF_CAPS_REF", caps["2"][3]))
out.append(blob("REF_DEVCAPS", by["devcaps"][0][2]))
dc = dict(kv.split("=") for kv in by["devcreate"][0])
out.append(f"#define REF_TEXMEM {dc['texmem']}u")
out.append("/* CheckDeviceFormat(adapter 0, HAL, adfmt, usage, rtype, fmt) */")
out.append(f"static const struct {{ uint8_t adfmt, rtype; uint16_t usage; uint32_t fmt, hr; }} REF_CDF[{len(by['cdf'])}] = {{")
c = by["cdf"]
out += ["    " + " ".join(f"{{{r[0]},{r[2]},0x{r[1]},0x{r[3]},0x{r[4]}}}," for r in c[i:i + 6]) for i in range(0, len(c), 6)]
out.append("};")
out.append("/* CheckDepthStencilMatch(adfmt, rtfmt, dsfmt) */")
c = by["cdsm"]
out.append(f"static const struct {{ uint8_t adfmt, rtfmt, dsfmt; uint32_t hr; }} REF_CDSM[{len(c)}] = {{")
out += ["    " + " ".join(f"{{{r[0]},{r[1]},{r[2]},0x{r[3]}}}," for r in c[i:i + 8]) for i in range(0, len(c), 8)]
out.append("};")
c = by["cdt"]
out.append(f"static const struct {{ uint8_t adfmt, windowed; uint32_t hr; }} REF_CDT[{len(c)}] = {{ " +
           " ".join(f"{{{r[0]},{r[1]},0x{r[2]}}}," for r in c) + " };")
c = by["cdms"]
out.append(f"static const struct {{ uint8_t adfmt, windowed, ms; uint32_t hr; }} REF_CDMS[{len(c)}] = {{")
out += ["    " + " ".join(f"{{{r[0]},{r[1]},{r[2]},0x{r[3]}}}," for r in c[i:i + 8]) for i in range(0, len(c), 8)]
out.append("};")
print("\n".join(out))
